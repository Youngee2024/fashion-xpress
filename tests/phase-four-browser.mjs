import assert from 'node:assert/strict'

const target = await fetch('http://127.0.0.1:9333/json/new?about:blank', { method: 'PUT' }).then((response) => response.json())
const socket = new WebSocket(target.webSocketDebuggerUrl)
await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', reject, { once: true }) })
let sequence = 0
const pending = new Map()
const events = new Map()
const network = []
const errors = []
socket.addEventListener('message', ({ data }) => {
  const message = JSON.parse(data)
  if (message.id) { const promise = pending.get(message.id); pending.delete(message.id); message.error ? promise.reject(new Error(message.error.message)) : promise.resolve(message.result); return }
  if (message.method === 'Network.requestWillBeSent' && (/\/api\//.test(message.params.request.url) || /supabase\.co/.test(message.params.request.url))) network.push(message.params.request.url)
  if (message.method === 'Runtime.exceptionThrown') errors.push(message.params.exceptionDetails?.text ?? 'Browser exception')
  const listeners = events.get(message.method) ?? []
  events.delete(message.method)
  listeners.forEach((resolve) => resolve(message.params))
})
function send(method, params = {}) { const id = ++sequence; socket.send(JSON.stringify({ id, method, params })); return new Promise((resolve, reject) => pending.set(id, { resolve, reject })) }
function once(method) { return new Promise((resolve) => events.set(method, [...(events.get(method) ?? []), resolve])) }
async function navigate(path) { const loaded = once('Page.loadEventFired'); await send('Page.navigate', { url: `http://127.0.0.1:4173${path}` }); await loaded; await new Promise((resolve) => setTimeout(resolve, 150)) }
async function evaluate(expression) { const result = await send('Runtime.evaluate', { expression, returnByValue: true }); if (result.exceptionDetails) throw new Error(result.exceptionDetails.exception?.description ?? result.exceptionDetails.text); return result.result.value }
async function settle() { await new Promise((resolve) => setTimeout(resolve, 180)) }

